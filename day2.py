# operator aritmatika dan type casting

# Membaca 2 pembacaan sensor dalam angka desimal (float)
sensor1 = float(input("Nilai sensor 1: "))
sensor2 = float(input("Nilai sensor 2: "))

# Mengukur rata-rata
rata_rata = (sensor1 + sensor2) / 2

print(f"Rata-rata nilai sensor: {rata_rata:.2f}")